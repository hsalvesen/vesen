/** A frame's size in cells; a cell is drawn two characters wide. */
export const NYAN_COLS = 64;
export const NYAN_ROWS = 64;

/**
 * The animation's pace: twelve frames to two beats of the track's 140 beats a minute, as the
 * original's twelve frames bob to the song.
 */
export const NYAN_FPS = 14;

/** Where the track's first beat falls, in seconds: the first frame starts on it. */
export const NYAN_BEAT_S = 0.16;

/** The sky behind it all, the original's blue. */
export const NYAN_SKY = '#003366';

/**
 * What a cell's character stands for: the two characters drawn for it, their colour, and the one
 * character of the still printed outside the terminal (nyancat's 40-column text mode).
 */
export interface NyanInk {
  readonly text: string;
  readonly colour: string;
  readonly still: string;
}

export const NYAN_INKS: Readonly<Record<string, NyanInk>> = {
  // The sky, a shade lighter than the blue behind it, and the stars.
  ',': { text: '::', colour: '#1b4f8a', still: '.' },
  '.': { text: '@@', colour: '#ffffff', still: '@' },
  // The black outline: the sky shows through it.
  "'": { text: '  ', colour: '#000000', still: ' ' },
  // The Pop-Tart: its crust, its frosting and the sprinkles.
  '@': { text: '##', colour: '#ffcc99', still: '#' },
  $: { text: '??', colour: '#ff99ff', still: '?' },
  '-': { text: '<>', colour: '#ff3399', still: 'O' },
  // The rainbow, from the top.
  '>': { text: '##', colour: '#ff0000', still: '#' },
  '&': { text: '==', colour: '#ff9900', still: '=' },
  '+': { text: '--', colour: '#ffff00', still: '-' },
  '#': { text: '++', colour: '#33ff00', still: '+' },
  '=': { text: '~~', colour: '#0099ff', still: '~' },
  ';': { text: '$$', colour: '#6633ff', still: '$' },
  // The cat, a little lighter than the original's grey so it shows on the sky, and its cheeks.
  '*': { text: ';;', colour: '#b3b3b3', still: ';' },
  '%': { text: '()', colour: '#ff99cc', still: 'o' },
};


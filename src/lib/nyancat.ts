/** A run of cells of one colour in a row, as drawn: their characters and the colour. */
export interface NyanRun {
  readonly text: string;
  readonly colour: string;
}

/** A frame's rows as runs of one colour, two characters a cell: what the app draws, a span a run. */
export function frameRuns(frame: readonly string[]): NyanRun[][] {
  return frame.map((row) => {
    const runs: { text: string; colour: string }[] = [];
    for (const cell of row) {
      const ink = NYAN_INKS[cell] ?? NYAN_INKS[','];
      if (ink === undefined) continue;
      const last = runs[runs.length - 1];
      if (last !== undefined && last.colour === ink.colour) last.text += ink.text;
      else runs.push({ text: ink.text, colour: ink.colour });
    }
    return runs;
  });
}

/** The frame on the screen `seconds` into the track: the first from its first beat, twelve to two beats. */
export function nyanFrameAt(seconds: number): number {
  const into = seconds - NYAN_BEAT_S;
  if (!Number.isFinite(into) || into <= 0) return 0;
  return Math.floor(into * NYAN_FPS) % NYAN_FRAMES.length;
}

/** The rows and columns a still shows: the cat and its rainbow, with a row of sky above and below. */
const STILL_ROWS = [21, 44] as const;
const STILL_COLS = 50;

/** A still of the first frame, a character a cell, as nyancat's 40-column mode draws it: for outside the terminal. */
export function stillNyan(): string {
  return (NYAN_FRAMES[0] ?? [])
    .slice(STILL_ROWS[0], STILL_ROWS[1])
    .map((row) => Array.from(row.slice(0, STILL_COLS), (cell) => NYAN_INKS[cell]?.still ?? ' ').join(''))
    .join('\n');
}
